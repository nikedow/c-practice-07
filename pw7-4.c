#include <stdio.h>
void assign_first(int *pa, int *pb, int *pc) {
    *pb = *pa;
    *pc = *pa;
}
int main(void) {
    int a = 10;
    int b = 25;
    int c = 40;
    printf("до вызова функции:    a = %d, b = %d, c = %d\n", a, b, c);
    assign_first(&a, &b, &c);
    printf("после вызова функции: a = %d, b = %d, c = %d\n", a, b, c);
    return 0;
}
/*
 * при передаче по значению функция получает только копии переменных, 
 * поэтому оригиналы в main() не меняются.
 * При передаче по указателю мы передаем реальные адреса памяти (&), 
 * и функция с помощью разыменования (*) изменяет сами оригиналы в main()
 */